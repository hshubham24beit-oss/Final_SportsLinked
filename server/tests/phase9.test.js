const request = require('supertest');
const {
  app,
  API,
  registerAndLogin,
  authHeader,
} = require('./helpers');
const config = require('../config/env');
const provider = require('../services/ai/provider');
const { resetAiRateLimits } = require('../services/ai/rateLimit');
const Post = require('../models/Post');

const PRIVATE_EVIDENCE_URL = 'https://private.example.test/evidence/secret-document.pdf';

function futureDate(days = 30) {
  return new Date(Date.now() + days * 24 * 60 * 60 * 1000).toISOString();
}

async function onboard(account, role, overrides = {}) {
  const base =
    role === 'athlete'
      ? {
          headline: 'Sprint athlete focused on national competition',
          bio: 'I train and compete in sprint events.',
          location: { city: 'Pune', region: 'Maharashtra', country: 'India' },
          sports: ['Athletics'],
          positions: ['100m'],
          level: 'professional',
          ageCategory: 'senior',
          competitionLevel: 'national',
          experienceYears: 6,
          currentTeam: 'Pune Striders',
          availableForTrials: true,
          personalBests: [
            {
              event: '100m',
              result: '11.8',
              unit: 'seconds',
              date: '2026-02-10',
              competition: 'State meet',
            },
          ],
        }
      : role === 'coach'
        ? {
            headline: 'Sprint coach',
            bio: 'I coach sprint athletes in Pune.',
            location: { city: 'Pune', region: 'Maharashtra', country: 'India' },
            sports: ['Athletics'],
            specializations: ['Sprints'],
            experienceYears: 9,
            availability: 'open_to_roles',
          }
        : {
            name: 'Pune Sports Academy',
            headline: 'Athletics academy',
            bio: 'A community athletics academy with sprint programmes.',
            location: { city: 'Pune', region: 'Maharashtra', country: 'India' },
            organizationType: 'academy',
            sports: ['Athletics'],
            foundedYear: 2012,
            activities: ['Sprint programme'],
          };

  const response = await request(app)
    .post(`${API}/profiles/onboarding`)
    .set(authHeader(account.accessToken))
    .send({ ...base, ...overrides });
  expect([200, 201]).toContain(response.status);
  return { ...account, profile: response.body.data.profile };
}

async function onboardAthlete(overrides) {
  const account = await registerAndLogin({ name: 'AI Athlete', role: 'athlete' });
  return onboard(account, 'athlete', overrides);
}

async function onboardCoach(overrides) {
  const account = await registerAndLogin({ name: 'AI Coach', role: 'coach' });
  return onboard(account, 'coach', overrides);
}

async function onboardAcademy(overrides) {
  const account = await registerAndLogin({ name: 'AI Recruiter', role: 'recruiter' });
  return onboard(account, 'recruiter', overrides);
}

function opportunityPayload(overrides = {}) {
  return {
    type: 'trials',
    title: 'Sprint trials in Pune',
    description: 'Open sprint trials for athletes with competition experience.',
    sport: 'Athletics',
    positions: ['100m'],
    deadline: futureDate(),
    location: { city: 'Pune', region: 'Maharashtra', country: 'India' },
    eligibility: {
      levels: ['professional'],
      competitionLevels: ['national'],
      ageCategories: ['senior'],
      minExperienceYears: 5,
    },
    ...overrides,
  };
}

async function publishOpportunity(owner, overrides = {}) {
  const created = await request(app)
    .post(`${API}/opportunities`)
    .set(authHeader(owner.accessToken))
    .send(opportunityPayload(overrides));
  expect(created.status).toBe(201);
  const published = await request(app)
    .post(`${API}/opportunities/${created.body.data.opportunity.id}/publish`)
    .set(authHeader(owner.accessToken));
  expect(published.status).toBe(200);
  return published.body.data.opportunity;
}

describe('Phase 9 AI assistance', () => {
  const originalRateLimit = config.ai.rateLimitMax;

  beforeEach(() => {
    jest.restoreAllMocks();
    resetAiRateLimits();
    config.ai.rateLimitMax = originalRateLimit;
  });

  afterAll(() => {
    config.ai.rateLimitMax = originalRateLimit;
    resetAiRateLimits();
  });

  it('returns labeled suggestions without saving or publishing anything', async () => {
    const athlete = await onboardAthlete();
    jest.spyOn(provider, 'generateText').mockResolvedValue({
      text: 'A reviewed draft generated by the configured provider.',
      configured: true,
    });

    const profile = await request(app)
      .post(`${API}/ai/profile-suggestion`)
      .set(authHeader(athlete.accessToken))
      .send({
        headline: athlete.profile.headline,
        bio: athlete.profile.bio,
        sports: ['Athletics'],
        positions: ['100m'],
        experienceYears: 6,
      });
    expect(profile.status).toBe(200);
    expect(profile.body.data.suggestion.label).toContain('Suggestion');
    expect(profile.body.data.suggestion.verified).toBe(false);

    const unchanged = await request(app)
      .get(`${API}/profiles/me`)
      .set(authHeader(athlete.accessToken));
    expect(unchanged.body.data.profile.bio).toBe(athlete.profile.bio);

    const draft = await request(app)
      .post(`${API}/ai/content-draft`)
      .set(authHeader(athlete.accessToken))
      .send({
        kind: 'post',
        topic: 'A training update',
        details: 'Completed a sprint session today.',
      });
    expect(draft.status).toBe(200);
    expect(draft.body.data.draft.label).toContain('Suggestion');
    expect(await Post.countDocuments()).toBe(0);

    const published = await request(app)
      .post(`${API}/posts`)
      .set(authHeader(athlete.accessToken))
      .send({ text: draft.body.data.draft.text, type: 'text', visibility: 'public' });
    expect(published.status).toBe(201);
    expect(await Post.countDocuments()).toBe(1);
  });

  it('enforces a per-user AI request limit', async () => {
    const athlete = await onboardAthlete();
    config.ai.rateLimitMax = 2;
    resetAiRateLimits();

    await request(app)
      .get(`${API}/ai/profile-recommendations`)
      .set(authHeader(athlete.accessToken))
      .expect(200);
    await request(app)
      .get(`${API}/ai/profile-recommendations`)
      .set(authHeader(athlete.accessToken))
      .expect(200);

    const limited = await request(app)
      .get(`${API}/ai/profile-recommendations`)
      .set(authHeader(athlete.accessToken));
    expect(limited.status).toBe(429);
    expect(limited.body.code).toBe('AI_RATE_LIMITED');
    expect(limited.headers['retry-after']).toBeDefined();
  });

  it('falls back to a deterministic draft when the provider fails', async () => {
    const athlete = await onboardAthlete();
    jest.spyOn(provider, 'generateText').mockResolvedValue({
      text: '',
      configured: true,
      error: 'timeout',
    });

    const response = await request(app)
      .post(`${API}/ai/profile-suggestion`)
      .set(authHeader(athlete.accessToken))
      .send({
        headline: athlete.profile.headline,
        bio: athlete.profile.bio,
        sports: ['Athletics'],
        experienceYears: 6,
        location: { city: 'Pune', country: 'India' },
      });

    expect(response.status).toBe(200);
    expect(response.body.data.suggestion.generatedBy).toBe('fallback');
    expect(response.body.data.suggestion.degraded).toBe(true);
    expect(response.body.data.suggestion.bio).toContain('Athletics');
    expect(response.body.data.suggestion.notice).toMatch(/unavailable/i);
  });

  it('never sends private evidence or unknown private fields to the provider', async () => {
    const athlete = await onboardAthlete();
    await request(app)
      .post(`${API}/achievements`)
      .set(authHeader(athlete.accessToken))
      .send({
        title: 'State sprint finalist',
        sport: 'Athletics',
        competition: 'State championships',
        result: 'Finalist',
        evidenceRefs: [{ url: PRIVATE_EVIDENCE_URL, label: 'Private document' }],
      })
      .expect(201);

    const generate = jest.spyOn(provider, 'generateText').mockResolvedValue({
      text: 'A safe suggestion.',
      configured: true,
    });

    const response = await request(app)
      .post(`${API}/ai/profile-suggestion`)
      .set(authHeader(athlete.accessToken))
      .send({
        headline: athlete.profile.headline,
        bio: athlete.profile.bio,
        sports: ['Athletics'],
        evidenceRefs: [{ url: PRIVATE_EVIDENCE_URL }],
        privateEvidenceUrl: PRIVATE_EVIDENCE_URL,
      });

    expect(response.status).toBe(200);
    const providerInput = JSON.stringify(generate.mock.calls[0][0]);
    expect(providerInput).not.toContain(PRIVATE_EVIDENCE_URL);
    expect(providerInput).not.toContain('evidenceRefs');
    expect(response.body.data.suggestion.bio).not.toContain(PRIVATE_EVIDENCE_URL);
  });

  it('recommends opportunities with displayed criteria and reasons', async () => {
    const athlete = await onboardAthlete();
    const coach = await registerAndLogin({ name: 'Opportunity Coach', role: 'coach' });
    const opportunity = await publishOpportunity(coach);

    const response = await request(app)
      .post(`${API}/ai/opportunity-matches`)
      .set(authHeader(athlete.accessToken))
      .send({
        sport: 'Athletics',
        positions: ['100m'],
        location: 'Pune, Maharashtra, India',
        experienceYears: 6,
        level: 'professional',
        competitionLevel: 'national',
        ageCategory: 'senior',
        preferredTypes: ['trials'],
      });

    expect(response.status).toBe(200);
    expect(response.body.data.criteria).toEqual(
      expect.arrayContaining([
        expect.objectContaining({ key: 'sport', value: 'Athletics' }),
        expect.objectContaining({ key: 'positions', value: '100m' }),
      ]),
    );
    expect(response.body.data.matches).toHaveLength(1);
    expect(response.body.data.matches[0].id).toBe(opportunity.id);
    expect(response.body.data.matches[0].matchScore).toBeGreaterThan(0);
    expect(response.body.data.matches[0].reasons.join(' ')).toMatch(/Sport matches/);
    expect(response.body.data.matches[0].reasons.join(' ')).toMatch(/Position matches/);
  });

  it('returns profile recommendations with visible matching reasons', async () => {
    const athlete = await onboardAthlete();
    const coach = await onboardCoach();
    const academy = await onboardAcademy();
    const teamResponse = await request(app)
      .post(`${API}/teams`)
      .set(authHeader(coach.accessToken))
      .send({
        name: 'Pune Sprint Team',
        description: 'A public sprint training team based in Pune.',
        sport: 'Athletics',
        type: 'team',
        privacy: 'public',
        location: { city: 'Pune', region: 'Maharashtra', country: 'India' },
      });
    expect(teamResponse.status).toBe(201);

    const response = await request(app)
      .get(`${API}/ai/profile-recommendations`)
      .set(authHeader(athlete.accessToken));
    expect(response.status).toBe(200);
    expect(response.body.data.criteria.length).toBeGreaterThan(0);
    const groups = response.body.data.groups;
    expect(groups.map((group) => group.key)).toEqual(
      expect.arrayContaining(['coaches', 'teams', 'academies']),
    );
    const coachGroup = groups.find((group) => group.key === 'coaches');
    expect(coachGroup.recommendations[0].id).toBe(
      coach.loginResponse.body.data.user.id,
    );
    expect(coachGroup.recommendations[0].reasons.length).toBeGreaterThan(0);
    const academyGroup = groups.find((group) => group.key === 'academies');
    expect(academyGroup.recommendations[0].id).toBe(
      academy.loginResponse.body.data.user.id,
    );
  });

  it('summarizes only structured performance records and shows the data', async () => {
    const athlete = await onboardAthlete();
    for (const entry of [
      { metric: '100m time', value: 12.1, unit: 'seconds', date: '2026-01-10' },
      { metric: '100m time', value: 11.8, unit: 'seconds', date: '2026-03-10' },
    ]) {
      await request(app)
        .post(`${API}/profiles/me/statistics`)
        .set(authHeader(athlete.accessToken))
        .send(entry)
        .expect(201);
    }

    const response = await request(app)
      .get(`${API}/ai/performance-insights`)
      .set(authHeader(athlete.accessToken));
    expect(response.status).toBe(200);
    const insights = response.body.data.insights;
    expect(insights.metricGroups).toHaveLength(1);
    expect(insights.metricGroups[0].records).toHaveLength(2);
    expect(insights.metricGroups[0].direction).toBe('decreased');
    expect(insights.metricGroups[0].summary).toMatch(/latest recorded value/i);
    expect(insights.personalBests).toHaveLength(1);
    expect(insights.disclaimer).toMatch(/does not assess athletic ability/i);
    expect(JSON.stringify(insights)).not.toContain(PRIVATE_EVIDENCE_URL);
  });
});
